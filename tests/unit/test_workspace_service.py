    @pytest.mark.asyncio
    async def test_should_create_workspace_with_valid_data(self):
        """Тест должен создать workspace с корректными данными"""
        # given
        mock_repository = Mock(spec=WorkSpaceRepository)
        mock_repository.add_participation = AsyncMock()
        mock_uow = Mock()
        mock_session = Mock()
        mock_result = Mock()
        mock_result.scalar_one_or_none.return_value = MANAGER_ROLE
        mock_session.execute = AsyncMock(return_value=mock_result)
        mock_uow.session = mock_session
        mock_repository.uow = mock_uow
        mock_workspace = WorkSpace(id=1, name="Test Workspace", author_id=1, status_id=1)
        mock_repository.create.return_value = mock_workspace

        workspace_service = WorkSpaceService(mock_repository)

        workspace_data = WorkSpaceCreate(name="Test Workspace", author_id=1, status_id=1)

        # when
        result = await workspace_service.create_workspace(workspace_data, author_id=1)

        # then
        assert result == mock_workspace
        mock_repository.create.assert_called_once_with(workspace_data)
        mock_repository.add_participation.assert_called_once_with(1, 1, MANAGER_ROLE.id)

