    @pytest.mark.asyncio
    async def test_should_get_workspaces_paginated(self):
        """Тест должен получить workspace с пагинацией"""
        # given
        mock_repository = Mock(spec=WorkSpaceRepository)
        mock_workspaces = [
            WorkSpace(id=1, name="Workspace 1", author_id=1, status_id=1),
            WorkSpace(id=2, name="Workspace 2", author_id=2, status_id=1),
        ]
        mock_repository.get_multi.return_value = mock_workspaces
        mock_repository.count.return_value = 2

        workspace_service = WorkSpaceService(mock_repository)

        # when
        workspaces, total = await workspace_service.get_workspaces_paginated(page=1, limit=10)

        # then
        assert workspaces == mock_workspaces
        assert total == EXPECTED_WORKSPACES_COUNT
        assert len(workspaces) == EXPECTED_WORKSPACES_COUNT
        mock_repository.get_multi.assert_called_once_with(skip=0, limit=10)
        mock_repository.count.assert_called_once()

